  /* ─── ENGINE ─────────────────────────────────────────── */
  var LANGS = ['en', 'es', 'fr', 'it'];
  var currentLang = 'en';

  function detect() {
    try {
      var saved = localStorage.getItem('bxp-lang');
      if (saved && T[saved]) return saved;
    } catch (e) {}
    var b = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return T[b] ? b : 'en';
  }

  function apply(lang) {
    if (!T[lang]) return;
    currentLang = lang;
    try { localStorage.setItem('bxp-lang', lang); } catch (e) {}
    document.documentElement.lang = lang;
    var dict = T[lang];

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = dict[el.dataset.i18n];
      if (v === undefined) return;
      if (el.tagName === 'TITLE') { document.title = v; }
      else if (el.tagName === 'OPTION') { el.textContent = v; }
      else { el.textContent = v; }
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var v = dict[el.dataset.i18nPh];
      if (v !== undefined) el.placeholder = v;
    });

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      var on = btn.dataset.lang === lang;
      btn.classList.toggle('active', on);
      btn.setAttribute('aria-pressed', String(on));
    });
  }

  /* Expose for forms.js (validation messages) */
  window.formsT = function (key) {
    return (T[currentLang] && T[currentLang][key]) || key;
  };
  window.formsLang = function () { return currentLang; };

  document.addEventListener('DOMContentLoaded', function () {
    apply(detect());
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () { apply(btn.dataset.lang); });
    });
  });
